/**
 * practice-signals — ЧИСТЫЕ величины, выведенные из практики тренера. Без I/O.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Эти правила (отсев разминок, личный пол лёгкой, запасной детектор
 * длительных, порог достаточности данных) — то, что правилось последние три наряда, и до
 * 13.08 они не были покрыты НИЧЕМ: жили внутри цикла с обращениями к базе, а все проверки
 * идут на заглушке конверта и это место не исполняют вовсе. Мутационный прогон это и показал:
 * порча отсева разминок и порога достаточности не роняла ни одной из 49 проверок.
 *
 * Здесь только вычисления. Кто и откуда взял строки — дело autoplanner-context.
 */

/** Заголовок качественной. Дубль константы контекста НАМЕРЕННО не делаем — она приходит извне. */
export type PlannedRun = { title: string; minutes: number };

/**
 * РАЗМИНКА/АКТИВАЦИЯ — НЕ ЛЁГКИЙ БЕГ.
 *
 * Замер 13.08: всё, что короче 40 мин у группы, — «Разминка» перед стартом (23 и 25 мин у
 * 5476215, 20/25/25 у 6009851). Без их отсева минимум атлета падает до 20-25, то есть ровно
 * в когортный пол, и личный пол теряет смысл.
 */
export const WARMUP_TITLE_RE = /разминк|активац|раскатк/i;

/**
 * БЛОК В СОРЕВНОВАТЕЛЬНОМ ТЕМПЕ — работа, а не обычная длительная.
 *
 * У 5475652 в верхнюю дециль попадали «25 км в темпе марафона» (180 мин) и «15 км в темпе
 * марафона» (132), и медиана длительных выходила 134 вместо 115.
 */
export const RACE_PACE_BLOCK_RE = /в темпе\s+(марафон|пм|полумарафон|мар\b)|марафонском темпе|соревновательн\w*\s+темп/i;

/**
 * «ТЕМП ВЫШЕ» — АЭРОБНЫЙ БЕГ ПО ЗАМЕРУ, а не качественный по регулярке.
 *
 * Измерено отдельным нарядом: 76% от порога против 83% у обычной лёгкой. QUALITY_TITLE_RE
 * держит его качественным, и трогать её нельзя — она кормит счётчики качества по всему
 * автопланировщику. Поэтому поправка живёт здесь, локально.
 */
export const AEROBIC_DESPITE_QUALITY_RE = /темп выше/i;

/**
 * ТЕМПОВЫЙ БЕГ — САМОСТОЯТЕЛЬНЫЙ ТИП КАЧЕСТВЕННОЙ, которого счётчики не видели.
 *
 * QUALITY_TITLE_RE ловит отрезки («8 х 4 мин»), «интерв», «отрезк», «порог», но НЕ ловит
 * «Темповый бег 30 минут» и «40 мин темп». Замер 12.08: 62 плановых темповых у 15 действующих
 * за 26 недель, и именно они у Паниной, Кругловой и Хофман стоят ВТОРОЙ качественной рядом
 * с отрезками. То есть вторая качественная была невидима не только отбору, но и статистике.
 *
 * «Бег по темпу» (1614 сессий) сюда НЕ входит и входить не должен: это режим контроля
 * («беги по заданному темпу»), а не тип тренировки. Та же ловушка, что «темп выше».
 *
 * ОСТОРОЖНО С КИРИЛЛИЦЕЙ: `\w` в JS не матчит русские буквы, поэтому `темпов\w*\s+бег`
 * молча не находит «Темповый бег». На этом сломался первый замер этого наряда.
 */
export const TEMPO_TITLE_RE = /(темпов[а-яё]*\s+бег|^\s*[0-9]{1,3}\s*(?:мин|минут|км)\s+темп|порогов[а-яё]*)/i;

/**
 * СТРУКТУРА ТЕМПОВОГО — ЗАМЕРЕНА 12.08 по описаниям тренера, не взята из литературы.
 *   разминка (n=41): min 10, медиана 15, p75 20
 *   заминка  (n=49): min  5, медиана 10, p75 10
 *   работа из заголовка (n=38): min 15, медиана 30, p75 40, max 60
 *   полная длительность (n=62): p25 56, медиана 60, p75 65
 * Берём медианы: 15 + работа + 10. При работе 30 выходит 55, при 40 — 65, то есть ровно
 * коридор практики. Сам диапазон работы задаёт КАТАЛОГ (steady_continuous: advisory 20–40,
 * duration_from_envelope), а не этот файл.
 */
export const TEMPO_WARMUP_MIN = 15;
export const TEMPO_COOLDOWN_MIN = 10;

/** Меньше этого числа пробежек за окно — личный пол не считаем, берём когортный. */
export const MIN_RUNS_FOR_PERSONAL_FLOOR = 20;

/** Верхняя доля не-качественных, из которой берётся запасная оценка длительной. */
export const LONG_FALLBACK_DECILE = 0.10;

export function median(values: number[]): number {
  if (!values.length) return 0;
  const s = [...values].sort((a, b) => a - b);
  return s.length % 2 ? s[(s.length - 1) / 2] : Math.round((s[s.length / 2 - 1] + s[s.length / 2]) / 2);
}

/**
 * Качественная ДЛЯ ЭТИХ РАСЧЁТОВ: как решает регулярка ПЛЮС темповый, но «темп выше» — аэробный,
 * а блок в соревновательном темпе — часть длительной, а не отдельная работа.
 *
 * ДВЕ ОШИБКИ В РАЗНЫЕ СТОРОНЫ, обе чинятся здесь: «темп выше» считался работой, хотя по замеру
 * это обычная лёгкая (парно внутри атлета разница темпа 0 с/км, заголовок «Легкий бег по темпу
 * (темп выше)»), а настоящий темповый работой НЕ считался вовсе.
 */
export function isQualityForPractice(title: string, qualityRe: RegExp): boolean {
  if (AEROBIC_DESPITE_QUALITY_RE.test(title)) return false;
  if (RACE_PACE_BLOCK_RE.test(title)) return false;
  return qualityRe.test(title) || TEMPO_TITLE_RE.test(title);
}

/** Темповый ли это (в отличие от отрезков) — нужно, чтобы знать тип второй качественной. */
export function isTempoForPractice(title: string, qualityRe: RegExp): boolean {
  return isQualityForPractice(title, qualityRe) && !qualityRe.test(title) && TEMPO_TITLE_RE.test(title);
}

/**
 * СКОЛЬКО КАЧЕСТВЕННЫХ ПРОСИТ ПРАКТИКА — ПО ПРОШЛОЙ НЕДЕЛЕ. [замер 12.08]
 *
 * Раньше это число выводилось из ЧИСЛА ДНЕЙ: две качественные скелет давал только с шести
 * беговых дней. В практике всё наоборот — у недель с двумя качественными медиана беговых
 * дней РАВНА ТРЁМ (77 недель из 164), шесть дней встретились ровно однажды. То есть
 * связь с числом дней была придумана, а не замерена, и отсекала как раз тех, кто две делает:
 * Панина, Круглова, Хофман бегают 3–4 дня.
 *
 * ЧЕМ ПРЕДСКАЗЫВАТЬ — ВЫБРАНО БЭКТЕСТОМ (1390 атлето-недель, из них 61 с двумя):
 *   прошлая неделя  точно 68.3%, |ошибка| 0.340, поймано 30/61, ложных 36
 *   среднее 4 нед   точно 66.6%, |ошибка| 0.358, поймано 21/61, ложных 27
 *   медиана 8 нед   точно 63.8%, |ошибка| 0.389, поймано 17/61, ложных 37
 *   p75 8 нед       точно 64.0%, |ошибка| 0.403, поймано 22/61, ложных 71
 *   «всегда 1»      точно 60.6%, |ошибка| 0.401, поймано  0/61 (нынешнее поведение)
 * Прошлая неделя выигрывает по всем осям сразу. Это ТА ЖЕ валюта и то же окно, которыми
 * уже считается число ДНЕЙ, так что новой сущности не заводится.
 *
 * ПОЛ РАВЕН ЕДИНИЦЕ: пустая прошлая неделя (болезнь, отпуск) не должна отменять качество —
 * за «можно ли вообще» отвечает отдельный гейт по истории 8 недель, а не эта функция.
 *
 * ПОТОЛОК ГЕЙТА ЗДЕСЬ СОЗНАТЕЛЬНО НЕ ПРИМЕНЯЕТСЯ. Первая версия зажимала число ещё и потолком,
 * и оно применялось ДВАЖДЫ — здесь и в rolesForDayCount. Мутационный прогон это и показал:
 * порча одного места полностью маскировалась вторым, то есть проверка «гейт главнее практики»
 * была беззубой не по своей вине. Ровно та же ловушка, что была с личными потолками, где
 * величина применялась в трёх местах. Потолок теперь ровно один — в скелете.
 */
export function qualityCountWanted(lastWeekQualityCount: number): number {
  return Math.max(1, lastWeekQualityCount);
}

/** Годится ли пробежка в выборку ЛИЧНОГО ПОЛА лёгкой. */
export function countsForEasyFloor(title: string, minutes: number, qualityRe: RegExp): boolean {
  if (!title || minutes <= 0 || minutes > 300) return false;
  if (isQualityForPractice(title, qualityRe)) return false;
  if (WARMUP_TITLE_RE.test(title)) return false;
  return true;
}

/** Годится ли пробежка в выборку ЗАПАСНОГО детектора длительных. */
export function countsForLongFallback(title: string, minutes: number, qualityRe: RegExp): boolean {
  if (!title || minutes <= 0 || minutes > 400) return false;
  if (isQualityForPractice(title, qualityRe)) return false;
  if (RACE_PACE_BLOCK_RE.test(title)) return false;
  return true;
}

/**
 * ЛИЧНЫЙ ПОЛ ЛЁГКОЙ — p10, а не min.
 *
 * Обосновано замером 13.08: min после отсева разминок выходит 40 у ДЕСЯТИ из двенадцати, то
 * есть схлопывается в когортную константу под личным именем; p10 даёт 40-55 и различает людей.
 * p10 симметричен правилу потолков «машине можно то, что тренер делает в девяти из десяти».
 */
export function easyFloorPersonal(samples: number[]): number {
  if (samples.length < MIN_RUNS_FOR_PERSONAL_FLOOR) return 0;
  const s = [...samples].sort((a, b) => a - b);
  return s[Math.floor(LONG_FALLBACK_DECILE * (s.length - 1))];
}

/**
 * ЗАПАСНАЯ ОЦЕНКА ДЛИТЕЛЬНОЙ — медиана верхней децили не-качественных.
 *
 * Нужна там, где тренер вообще не пишет в заголовке «длительная»: у 5748681 из 100 плановых
 * пробежек заголовку не отвечает НИ ОДНА, при этом пять её сессий по 100 мин названы
 * «Лёгкий бег (темп выше)». Проверено против эталона там, где заголовки есть (n=11): точное
 * совпадение у 5, средняя |ошибка| 9.5 мин, НИ РАЗУ не ниже эталона — для пола это правильная
 * сторона ошибки.
 */
export function longRunFallback(nonQualSamples: number[]): number {
  if (!nonQualSamples.length) return 0;
  const desc = [...nonQualSamples].sort((a, b) => b - a);
  return median(desc.slice(0, Math.max(1, Math.ceil(desc.length * LONG_FALLBACK_DECILE))));
}

/**
 * ЛИЧНАЯ ЦЕЛЬ И ЛИЧНЫЙ ПОТОЛОК ЛЁГКОЙ. Замер 13.08 по группе 12:
 *   собственная МЕДИАНА лёгкой выше цели тира у 10 из 12 (у 5475652 70 против 40);
 *   собственный p90 выше когортного потолка 70 у 10 из 12 (80..105).
 * То есть тирные 40/50/60 и потолок 70 — когортные числа в роли ЛИЧНЫХ пределов, шестая
 * правка одной природы. Личная величина в данных есть, поэтому берётся она.
 *
 * Цель — МЕДИАНА (правило «цели из медианы»), потолок — p90 (правило «потолки из p90»).
 * При нехватке данных обе возвращают 0, и сборщик остаётся на когортных.
 */
export function easyTargetPersonal(samples: number[]): number {
  if (samples.length < MIN_RUNS_FOR_PERSONAL_FLOOR) return 0;
  return median(samples);
}

export function easyMaxPersonal(samples: number[]): number {
  if (samples.length < MIN_RUNS_FOR_PERSONAL_FLOOR) return 0;
  const s = [...samples].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.floor(0.90 * (s.length - 1)))];
}

export type LongPractice = { maxMin: number; medianMin: number; fromFallback: boolean };

/**
 * ПРАКТИКА ДЛИТЕЛЬНЫХ: по заголовкам, а при их полном отсутствии — запасным детектором.
 *
 * Запасной включается ТОЛЬКО при полном отсутствии заголовков. Порог «мало заголовков»
 * (например меньше трёх) сознательно НЕ введён: у 5475652 он поднял бы медиану 90 -> 126,
 * и это решение тренера, а не моё.
 */
export function longRunPractice(titledSamples: number[], nonQualSamples: number[]): LongPractice {
  if (titledSamples.length > 0) {
    const s = [...titledSamples].sort((a, b) => a - b);
    return { maxMin: s[s.length - 1], medianMin: median(s), fromFallback: false };
  }
  const fb = longRunFallback(nonQualSamples);
  return { maxMin: fb, medianMin: fb, fromFallback: true };
}
