/**
 * Как выглядит тренировка у человека на дорожке: разминка по шагам и обвязка.
 *
 * ── ЗАЧЕМ [28.09.2026] ──────────────────────────────────────────────────────
 *
 * Генератор ставил «Разминка, спокойно, 21 минута» одним куском. Тренер ту же
 * 21 минуту пишет рукой иначе: ходьба, лёгкий бег, ускорения, спокойный бег.
 * Для новичка это несравнимо понятнее — он видит, ЧТО делать, а не сколько
 * терпеть. Неделю 28.09 пришлось править руками по месту; чтобы первая
 * перегенерация это не откатила, структура переезжает в код.
 *
 * ── ПОЧЕМУ ТРИ МИНУТЫ НА УСКОРЕНИЯ, А НЕ ДВЕ ────────────────────────────────
 *
 * Три ускорения по 20 секунд и две паузы по 40 между ними дают 2:20. В две
 * минуты это не лезет — поймано тренером на первой версии текста. Числа здесь
 * не круглые для красоты, они обязаны сходиться с тем, что человек делает.
 *
 * ── ПОРЯДОК УСТУПОК, КОГДА РАЗМИНКА КОРОТКАЯ ────────────────────────────────
 *
 * Разминка не всегда 21 минута: у другого формата она короче. Сокращаем не
 * пропорционально, а по важности — ходьба и лёгкий бег остаются до конца,
 * первым уходит «спокойный бег» перед работой, вторым ускорения. Пропорция
 * размазала бы ускорения в 40 секунд, то есть в ничто.
 *
 * ЧИСТЫЕ ФУНКЦИИ, БЕЗ КАТАЛОГА И БЕЗ БАЗЫ: их гоняет check:treadmill-shape.
 */

export type ShapePart = { minutes: number; label: string; text: string };

/** Ходьба в начале — фиксированные пять минут: это разогрев, а не тренировка. */
export const WALK_IN_MIN = 5;
/** Ускорения: 3 x 20 сек плюс две паузы по 40 = 2:20, округляем до трёх. */
export const STRIDES_MIN = 3;
/** Спокойный бег между ускорениями и работой. */
export const SETTLE_MIN = 3;
/** Ниже этого лёгкий бег в разминке смысла не имеет. */
export const EASY_MIN = 5;

/**
 * СКОРОСТЬ СЛОВАМИ, ПО ТОЙ ЖЕ ПРИЧИНЕ, ЧТО И УСКОРЕНИЯ. Обратный разбор считает
 * сегментом не только длительность, но и ДИСТАНЦИЮ: «6 км» внутри «5-6 км/ч»
 * добавляло лишний сегмент, и неделя уходила в round_trip_mismatch.
 */
const WALK: ShapePart = { minutes: WALK_IN_MIN, label: "Ходьба", text: "Спокойный шаг, пять-шесть км/ч." };
const EASY = (minutes: number): ShapePart => ({
  minutes, label: "Лёгкий бег", text: "Та же скорость, что на прошлой лёгкой.",
});
/**
 * ЧИСЛА ЗДЕСЬ СЛОВАМИ, И ЭТО НЕ СТИЛЬ [28.09.2026].
 *
 * Описание сессии проверяется обратным разбором (verifyRoundTrip): парсер
 * считает сегменты по длительностям вида «20 секунд». Цифры внутри пояснения
 * он принимал за два лишних сегмента, и ВСЯ неделя уходила в отказ
 * round_trip_mismatch. Парсер общий с ростером, трогать его нельзя.
 *
 * Словами он их не видит, а человек читает так же понятно.
 */
const STRIDES: ShapePart = {
  minutes: STRIDES_MIN, label: "Перед работой",
  text: "Три ускорения по двадцать секунд, между ними сорок секунд отдыха.",
};
const SETTLE: ShapePart = {
  minutes: SETTLE_MIN, label: "Спокойный бег", text: "Вернуться в ровный ритм и начинать.",
};

/**
 * Разминка по шагам. Сумма минут ВСЕГДА равна заданной: обвязка считается от
 * бюджета сессии, и потерянная минута уехала бы в расхождение с длительностью.
 */
export function treadmillWarmupParts(totalMinutes: number): ShapePart[] {
  const total = Math.round(totalMinutes);
  if (total < WALK_IN_MIN + EASY_MIN) {
    // Слишком коротко, чтобы делить: один блок честнее четырёх огрызков.
    return [{ minutes: total, label: "Разминка", text: "Спокойно, дыхание ровное." }];
  }
  const full = total - WALK_IN_MIN - STRIDES_MIN - SETTLE_MIN;
  if (full >= EASY_MIN) return [WALK, EASY(full), STRIDES, SETTLE];

  const noSettle = total - WALK_IN_MIN - STRIDES_MIN;
  if (noSettle >= EASY_MIN) return [WALK, EASY(noSettle), STRIDES];

  return [WALK, EASY(total - WALK_IN_MIN)];
}

/** Заминка: подпись без внутренних ярлыков, человек читает её на бегу. */
export function treadmillCooldown(minutes: number): ShapePart {
  return {
    minutes: Math.round(minutes),
    label: "Заминка, спокойный бег или шаг",
    text: "Пока дыхание не вернётся в норму.",
  };
}

/**
 * Обвязка аэробной тренировки: ходьба, основная часть, заминка.
 *
 * ЗАЧЕМ ОНА ЛЁГКОЙ И ДЛИТЕЛЬНОЙ. Генератор отдавал их ОДНИМ сегментом на все
 * 55 минут, а тренер и там пишет ходьбу в начале и шаг в конце. Человеку на
 * дорожке это ещё нужнее: «просто беги 55 минут» не говорит, с чего начать.
 *
 * Слишком короткую сессию не делим: у 15 минут обвязка съела бы половину.
 */
export function treadmillAerobicParts(input: {
  minutes: number;
  label: string;
  text: string;
}): ShapePart[] {
  const total = Math.round(input.minutes);
  const cooldown = 3;
  const main = total - WALK_IN_MIN - cooldown;
  if (main < 15) return [{ minutes: total, label: input.label, text: input.text }];
  return [
    { minutes: WALK_IN_MIN, label: "Ходьба", text: "Спокойный шаг, пять-шесть км/ч, разогреться." },
    { minutes: main, label: input.label, text: input.text },
    treadmillCooldown(cooldown),
  ];
}
