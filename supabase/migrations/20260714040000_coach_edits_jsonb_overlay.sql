-- Правки тренера переезжают в ОВЕРЛЕЙ-СЛОЙ и перестают жить внутри nutrition_summary.
--
-- ЗАЧЕМ. Перегенерация разбора пишет nutrition_summary целиком через upsert
-- (createNutritionWeeklyAnalysis, onConflict student_id,week_from,week_to). Всё, что
-- тренер правил ВНУТРИ summary — проза дней, фокус недели, тёплое открытие — при этом
-- стиралось МОЛЧА и без следа. Это случилось по-настоящему: Пономарёва, день 10.07.2026,
-- правку тренера снесла перегенерация, запущенная агентским прогоном.
--
-- КАК ЧИНИТ. Текст тренера уезжает ЗА ПРЕДЕЛЫ перезаписываемого блоба: модель по-прежнему
-- пишет athlete_prose внутри nutrition_summary, тренер пишет в coach_edits, а рендер
-- предпочитает тренера. Перегенерация переписывает athlete_prose и физически не может
-- задеть coach_edits — их там просто нет.
--
-- БЕЗОПАСНОСТЬ. coach_edits — мёртвый пережиток первого MVP: колонка есть, но её никто
-- никогда не читал и не писал. Проверено на живой базе 14.07.2026: 60 разборов, значений
-- НЕ-NULL — ноль. Преобразовывать нечего, USING ниже — формальность.
alter table public.nutrition_weekly_analyses
  alter column coach_edits type jsonb
  using nullif(coach_edits, '')::jsonb;

comment on column public.nutrition_weekly_analyses.coach_edits is
  'Оверлей правок тренера: { day_prose: { "ГГГГ-ММ-ДД": текст }, one_focus_statement_ru, athlete_opening_note_ru }. Переживает перегенерацию: модель пишет в nutrition_summary, тренер — сюда, рендер предпочитает это. Отсутствие ключа = тренер не правил (модельный текст). Удаление ключа = откат к модельному тексту.';
