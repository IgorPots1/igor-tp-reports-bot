-- Убираем user_agent из ответов подборщика кроссовок.
--
-- В ответах есть вес и история травм — данные о здоровье, — и человеку на
-- последнем шаге опросника обещано, что технических следов браузера мы не
-- пишем. Обещание должно держаться не только кодом, но и схемой: пока колонка
-- существует, любой следующий insert может её заполнить по недосмотру.
--
-- Отдельной миграцией, а НЕ правкой предыдущей: та могла быть уже применена, и
-- тогда изменение в ней молча не сработало бы. `if exists` делает шаг
-- безопасным в обоих случаях — и на живой таблице с колонкой, и на свежей
-- базе, где её никогда не было.
alter table public.shoe_picker_answers
  drop column if exists user_agent;
