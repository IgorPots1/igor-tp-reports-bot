-- Робот календаря: новый источник runc.run (Беговое сообщество — Московский марафон, Московский
-- полумарафон, «Белые ночи», «Северная столица» и др.), наряд 29.10.2026. По воскресеньям в 22:25 UTC,
-- между сбором d (22:24) и otime (22:27), до склейки (22:31) — старты runc склеиваются с probeg/ручными.
-- Применять ТОЛЬКО после выкатки edge-функции race-calendar-sync с источником runc (иначе стадия
-- вернёт «unknown source»). Аддитивно: одно задание pg_cron, ничего не удаляет.
select cron.schedule(
  'race-calendar-scrape-runc',
  '25 22 * * 0',
  $$select public.race_calendar_run_stage('scrape', 'runc')$$
);
