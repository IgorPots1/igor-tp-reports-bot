-- Правка предыдущей миграции (20261020000002) до первой записи в колонку —
-- строк с week_note не заполнено ни одной. Оказалось, что заметок к неделе
-- НЕ ОДНА: у Валентины их две ("про дорожку" без заголовка, всегда видна
-- сверху; "обязательно записывайте скорость" с заголовком, отдельным блоком).
-- text на одну заметку это не выражает — меняем на jsonb-массив SessionNote-подобных
-- объектов (title: string | null, body: string). title=null — верхний
-- баннер без заголовка; title задан — отдельная карточка с ним.
alter table intervals_plan_cycles drop column if exists week_note;
alter table intervals_plan_cycles add column if not exists week_notes jsonb;

comment on column intervals_plan_cycles.week_notes is
  'Заметки к неделе целиком, массив {title: string|null, body}. title=null — баннер '
  'без заголовка наверху экрана (дорожка/дыхание). title задан — отдельная видимая '
  'карточка с этим заголовком (например «Обязательно: записывайте скорость»). '
  'Не копируются в описание отдельных тренировок.';
