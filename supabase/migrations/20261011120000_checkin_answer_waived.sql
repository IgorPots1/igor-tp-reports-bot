-- Чек-ин можно закрыть БЕЗ ответа [наряд Игоря, 11.10.2026].
--
-- ЗАЧЕМ. «Неотвеченные» на карточке — это очередь работы тренера, и она должна
-- быть честной. Чек-ин от 20 сентября провисел три недели: отвечать на него
-- сейчас хуже, чем не отвечать (человек давно живёт другой неделей), но и
-- висеть в очереди он не должен — очередь, в которой есть строки, которые
-- никто никогда не закроет, перестаёт читаться целиком.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ КОЛОНКА, А НЕ ПУСТОЕ СООБЩЕНИЕ ТРЕНЕРА. Пустой ответ в
-- intervals_coach_messages соврал бы дважды: ученица увидела бы пустоту в
-- приложении, а в истории переписки осталась бы запись об ответе, которого не
-- было. Отказ отвечать — решение тренера о СВОЕЙ очереди, и жить он должен
-- рядом с чек-ином, а не в корпусе сообщений.
--
-- Аддитивно: две пустые колонки.
alter table public.intervals_checkins
  add column if not exists answer_waived_at timestamptz,
  add column if not exists answer_waived_by text;

comment on column public.intervals_checkins.answer_waived_at is
  'Тренер закрыл чек-ин без ответа. Ученица об этом не узнаёт: её экран не меняется.';
