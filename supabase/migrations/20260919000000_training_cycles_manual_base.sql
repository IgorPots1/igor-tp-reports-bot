-- training_cycles: ручная база от тренера.
--
-- НЕ ПРИМЕНЯЕТСЯ ЭТИМ НАРЯДОМ — только файл.
--
-- ЗАЧЕМ. Провал и спад формы в данных НЕРАЗЛИЧИМЫ, и автоматически это не выводится.
-- Два подтверждённых Игорем случая с одинаковой картиной в цифрах и противоположным смыслом:
--   Пономарева — сорвавшаяся марафонская подготовка, то есть ПРОВАЛ: верна база за 26 недель;
--   Расницова  — снизилась по семейным обстоятельствам, то есть НОВАЯ НОРМА:
--                база за 26 недель её ЗАВЫШАЕТ, верна восьминедельная.
-- У обеих 8-недельная база ниже 26-недельной на 58-59 минут [практика] — по данным они
-- выглядят одинаково. Различает их только тренер, поэтому нужен явный оверрайд.
--
-- ПОВЕДЕНИЕ: если поле заполнено — расчёт из истории для него НЕ применяется.
-- Пусто — считается как раньше (26 недель со взвешиванием по свежести).

alter table public.training_cycles
  add column if not exists base_aerobic_min_manual integer check (base_aerobic_min_manual >= 0),
  add column if not exists base_quality_min_manual integer check (base_quality_min_manual >= 0),
  add column if not exists base_manual_reason text;

comment on column public.training_cycles.base_aerobic_min_manual is
  'Аэробная база, заданная ТРЕНЕРОМ. Заполнено — расчёт из истории не применяется. Нужно там, где провал и новая норма в данных неразличимы (случай Расницовой против Пономаревой).';
comment on column public.training_cycles.base_quality_min_manual is
  'То же для минут работы. Пусто — считается из истории.';
comment on column public.training_cycles.base_manual_reason is
  'Зачем тренер переопределил базу — своими словами. Нужно, чтобы через полгода было понятно, почему у человека база не из истории.';
