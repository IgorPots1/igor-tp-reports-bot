-- Заметки недели живут у НЕДЕЛИ, а не у цикла [наряд Игоря, 06.10.2026].
--
-- ЧТО БЫЛО. buildWeek считает заметки на каждую неделю (ступень лестницы,
-- перерыв, снятые гейты, срезанные полы), а intervals-regenerate не писал их
-- НИКУДА: ни сессионные, ни недельные. Причина решения жила одной строкой в
-- stdout раннера и исчезала вместе с окном терминала. В плане, который тренер
-- читает через неделю, ответа на «почему здесь тот же формат» не было.
--
-- ПОЧЕМУ НЕ В intervals_plan_cycles.week_notes, КОТОРОЕ УЖЕ ЕСТЬ. Оно
-- цикл-уровневое: один массив на все 14 недель, и ученице показывается всегда,
-- независимо от того, про какую неделю заметка. Положить туда per-week разбор
-- значило бы показывать человеку заметку про чужую неделю. Эта таблица —
-- ровно (цикл, неделя), то есть единственное место, где такая заметка не врёт
-- адресом. Прежнее поле остаётся как есть: там лежат цикл-уровневые заметки
-- тренера, их поведение не меняется.
--
-- ВНУТРИ КАЖДОЙ ЗАМЕТКИ ЕСТЬ ПРИЗНАК АДРЕСАТА (audience: student | coach),
-- см. SessionNote в src/features/intervals/loop/types.ts. Отсутствие признака
-- читается как "student" — потому что все заметки, написанные до этой правки,
-- писал человек для ученицы.
--
-- Аддитивно: одна новая колонка, пустая по умолчанию.
alter table public.intervals_plan_weeks
  add column if not exists notes jsonb;

comment on column public.intervals_plan_weeks.notes is
  'Заметки к этой неделе: [{title, body, audience}]. audience=coach — только тренеру, отсутствие признака читается как student.';
