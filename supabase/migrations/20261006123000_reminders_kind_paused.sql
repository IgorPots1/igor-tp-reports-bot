-- paused в допустимых видах следа напоминаний [06.10.2026].
--
-- ЗАЧЕМ СЛЕД У МОЛЧАНИЯ. Раннер, встретив ученика на паузе, не отправляет
-- ничего — и без строки это выглядело бы ровно как «раннер не ходил». Отличать
-- два случая задним числом невозможно (та же причина, по которой след пишется
-- при любом status, см. intervals-reminders.ts), а здесь цена ошибки выше
-- обычной: тренер поставил человека на паузу и хочет видеть, что она
-- действует, а не верить на слово.
--
-- ВИД ОДИН НА СУТКИ. Констрейнт intervals_reminders_once_per_day
-- (source_id, kind, local_date) делает запись идемпотентной: раннер ходит
-- каждые полчаса, строка остаётся одна, повтор отбивается duplicate key,
-- который код уже молча проглатывает.
--
-- Прецедент, из-за которого это делается миграцией, а не только кодом: вид
-- weekly_form завели в коде без констрейнта, след не писался ВООБЩЕ, и
-- недельная форма уходила каждые полчаса (20260920_reminders_kind_weekly_form).
--
-- СПИСОК ВЗЯТ ИЗ БАЗЫ, А НЕ ИЗ ПРЕДЫДУЩЕЙ МИГРАЦИИ. В боевом констрейнте уже
-- был вид week_updated, которого нет ни в одном файле миграций (добавлен
-- руками через SQL-редактор, как и бо'льшая часть истории этой базы). Собери
-- список по файлу — и week_updated тихо выпал бы из допустимых, то есть след
-- уведомления об изменении недели перестал бы писаться, и неделя могла бы
-- переотдаваться по кругу: ровно та авария, которую закрывала миграция
-- 20260920. Перед правкой констрейнт прочитан из pg_constraint.
--
-- Расширение check-констрейнта, аддитивно: список видов только удлиняется.
alter table public.intervals_reminders
  drop constraint if exists intervals_reminders_kind_check;

alter table public.intervals_reminders
  add constraint intervals_reminders_kind_check
  check (kind in (
    'today_session', 'checkin_nudge', 'missed_nudge',
    'plan_published', 'weekly_form', 'week_updated', 'paused'
  ));
