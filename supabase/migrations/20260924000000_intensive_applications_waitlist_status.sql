-- intensive_applications: добавить статус 'waitlist' (лист ожидания).
--
-- НЕ ПРИМЕНЯЕТСЯ ЭТИМ НАРЯДОМ — только файл. Применяет Игорь.
--
-- ЗАЧЕМ. До этой правки /api/intensive/apply при нуле свободных мест возвращал
-- 409 и НЕ создавал анкету. Отказ происходил до вставки, до загрузки файлов и
-- до уведомления в Telegram, и не писал ни строки в лог — то есть заявка
-- человека исчезала БЕЗ ЕДИНОГО СЛЕДА: ни строки в таблице, ни файла в bucket,
-- ни сообщения тренеру. Восстановить такие анкеты невозможно.
--
-- ЦЕНА УЖЕ ЗАПЛАЧЕНА: поток 28 набрался к 14.08 19:59 МСК (10-я анкета), и всё,
-- что подавали после, потерялось. Сколько именно — база не знает и знать не
-- может; единственный возможный след это логи запросов Vercel (409 на
-- /api/intensive/apply), в приложении следов нет.
--
-- ЧТО МЕНЯЕТСЯ. Анкета сохраняется ВСЕГДА. Если мест нет — она приходит со
-- статусом 'waitlist'. Место в потоке занимают только 'new' и 'confirmed';
-- 'waitlist' и 'cancelled' не занимают. Кого пустить в набор — решает тренер
-- вручную в админке, а не арифметика на входе.
--
-- БЕЗОПАСНОСТЬ ДЛЯ СУЩЕСТВУЮЩИХ СТРОК: меняется ТОЛЬКО check-констрейнт, и
-- только в сторону расширения набора допустимых значений. Ни одна строка не
-- удаляется и не переписывается, статусы имеющихся анкет остаются как есть.
-- На 16.08 в таблице 10 анкет, все со статусом 'new' — они под новый
-- констрейнт проходят без изменений.

alter table public.intensive_applications
  drop constraint if exists intensive_applications_status_check;

alter table public.intensive_applications
  add constraint intensive_applications_status_check
  check (status in ('new', 'confirmed', 'waitlist', 'cancelled'));

comment on column public.intensive_applications.status is
  'new — пришла и ждёт тренера; confirmed — место подтверждено; waitlist — подана при отсутствии свободных мест, ждёт решения тренера; cancelled — человек отказался или не подошёл. Место в потоке занимают ТОЛЬКО new и confirmed. Перевод waitlist -> new/confirmed делает тренер вручную; лимит при этом не блокирует, а только предупреждает.';
