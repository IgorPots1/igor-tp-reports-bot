-- ГРАНТЫ service_role на две новые таблицы. ИСПРАВЛЕНИЕ ДЕФЕКТА, а не новая функция.
--
-- НЕ ПРИМЕНЯЕТСЯ ЭТИМ НАРЯДОМ — только файл.
--
-- ЧТО СЛОМАНО. Миграция 20260922000000 создала billing_email_import_attempts, но НЕ ВЫДАЛА
-- прав service_role. Проверка 13.08 после её применения:
--   select из billing_email_import_attempts → 42501 permission denied,
--   подсказка Postgres: GRANT SELECT ON public.billing_email_import_attempts TO service_role.
-- Приложение ходит в базу ТОЛЬКО ключом service_role, значит журнал входящих вызовов импорта
-- не пишется вовсе.
--
-- ПОЧЕМУ ЭТО ОСОБЕННО ПЛОХО ИМЕННО ЗДЕСЬ. Вставка в журнал в маршруте обёрнута в try/catch
-- и ошибка ПРОГЛАТЫВАЕТСЯ НАМЕРЕННО — чтобы падение журнала никогда не роняло сам импорт
-- платежей. То есть отсутствие гранта не даёт ни ошибки, ни строки: журнал выглядит рабочим
-- и молчит. А заводился он ровно для того, чтобы различить «вызов не пришёл» и «вызов пришёл
-- и упал на входе», и молчащий журнал отвечает на этот вопрос неверно — «вызовов не было».
--
-- Соседние таблицы того же импорта грант имеют с самого начала
-- (20260526161000: billing_email_import_runs, billing_email_import_attachments) —
-- то есть это именно пропуск в моей миграции, а не смена правил.
--
-- athlete_week_preferences (20260924000000) добавлена сюда же превентивно: на чтение права
-- у неё оказались, но писать в неё ещё некому, и обнаружился бы тот же пропуск только в тот
-- день, когда тренер заведёт первое пожелание. Гранты идемпотентны, повтор безвреден.
--
-- RLS не трогаем: она остаётся default-deny для anon/authenticated. Права выдаются ровно
-- той роли, которой ходит приложение.

grant select, insert, update, delete on table public.billing_email_import_attempts to service_role;
grant select, insert, update, delete on table public.athlete_week_preferences to service_role;
