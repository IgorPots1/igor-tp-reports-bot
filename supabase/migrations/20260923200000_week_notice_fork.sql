-- Развилка текста уведомления об отданной неделе [23.09.2026].
--
-- Текст был один, «План готов». Для новой недели это правда, но тренер жмёт ту
-- же кнопку, дописывая один день в неделю, которую ученица уже видит, — и
-- человек получает «план готов» про план, который у него неделю как есть.
-- Живой случай: 23.09 в текущую неделю добавили одну пятницу, и Валентине ушло
-- «План готов».
--
-- Две добавки, обе аддитивные:
--
-- 1. НОВЫЙ ВИД НАПОМИНАНИЯ week_updated. Отдельный вид, а не второй текст под
--    старым: ключ (источник, вид, дата) гасит повтор в тот же день, и если бы
--    вид был общий, «отдал новую неделю» и «дописал день» не могли бы уйти
--    одним днём.
--
-- 2. СКОЛЬКО ТРЕНИРОВОК БЫЛО В НЕДЕЛЕ НА МОМЕНТ ОТДАЧИ. Без этого числа нельзя
--    честно сказать «добавил тренировку»: по статусу видно только «отдавали
--    раньше или нет», а тренер мог и просто переписать существующую.
--    NULL у старых недель — «не знаем», и код в этом случае говорит «поправил»,
--    а не догадывается в сторону «добавил».

alter table public.intervals_reminders
  drop constraint if exists intervals_reminders_kind_check;

alter table public.intervals_reminders
  add constraint intervals_reminders_kind_check
  check (kind in ('today_session', 'checkin_nudge', 'missed_nudge', 'plan_published', 'weekly_form', 'week_updated'));

alter table public.intervals_plan_weeks
  add column if not exists released_session_count integer;

comment on column public.intervals_plan_weeks.released_session_count is
  'Сколько тренировок было в неделе на момент последней отдачи ученице. NULL — неделю отдавали до появления колонки, сравнивать не с чем.';
