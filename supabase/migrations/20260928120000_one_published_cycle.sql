-- Один опубликованный цикл на ученика — правилом БАЗЫ, а не только кода [28.09.2026].
--
-- ПОВОД. Тренер увидел в списке циклов две строки со статусом published и
-- спросил, не выстрелит ли это однажды. Проверка показала, что инвариант цел:
-- циклы принадлежали РАЗНЫМ источникам (Валентина и служебная карточка), а
-- publishCycle честно гасит прежние в superseded перед публикацией нового.
--
-- Но держался инвариант ТОЛЬКО на коде. Один путь публикации, который забудет
-- позвать supersede, — и у человека два плана сразу, причём тихо: getPublishedCycle
-- берёт свежайший по published_at и вторую строку просто не заметит. Симптом
-- проявится не здесь, а через неделю, когда отданные недели одного цикла
-- перестанут совпадать с сессиями другого.
--
-- Частичный уникальный индекс делает это невозможным. Он аддитивен и совместим
-- с нынешним порядком действий: publishCycle сперва переводит прежние в
-- superseded и только потом публикует новый, то есть двух published одновременно
-- не бывает даже на мгновение.
--
-- ПРОВЕРЕНО ПЕРЕД СОЗДАНИЕМ: нарушающих строк нет (по одному published на оба
-- живых источника), поэтому индекс встанет без починки данных.

create unique index if not exists intervals_plan_cycles_one_published_uidx
  on public.intervals_plan_cycles (source_id)
  where status = 'published';

comment on index public.intervals_plan_cycles_one_published_uidx is
  'Один published-цикл на источник. Второй published теперь невозможен: publishCycle гасит прежние ДО публикации, а этот индекс ловит любой путь, который это забудет.';
