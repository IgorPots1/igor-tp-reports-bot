-- Модель структурированного шага для ручного авторства плана [решение Игоря,
-- 17.09.2026]: шаг с длительностью, ориентиром, названием и пояснением;
-- вложенные повторы (repeat); пояснения к тренировке целиком отдельно от
-- шагов; заметка к неделе целиком отдельно от каждой тренировки.
--
-- Аддитивно и параллельно существующей `segments` (плоский Segment[] от
-- автогенератора — она никого не переживает и не трогается). Новые колонки
-- nullable: старые строки (сгенерированные) читаются как раньше, рендер
-- переключается на новую структуру только когда steps реально заполнены.
alter table intervals_plan_sessions
  add column if not exists steps jsonb,
  add column if not exists notes jsonb;

comment on column intervals_plan_sessions.steps is
  'Структурированные шаги (SessionStep[] — минуты, ориентир, название, пояснение, '
  'необязательный вложенный повтор). Заполняется только при ручном авторстве плана. '
  'NULL — сессия от автогенератора, структура в segments как раньше.';

comment on column intervals_plan_sessions.notes is
  'Пояснения к тренировке целиком (SessionNote[] — заголовок + текст), отдельно от '
  'шагов — «как подобрать скорость», «почему 55, а не 70». Показываются свёрнутой '
  'карточкой внизу, не смешиваются с шагами.';

alter table intervals_plan_cycles
  add column if not exists week_note text;

comment on column intervals_plan_cycles.week_note is
  'Заметка к неделе целиком (про дорожку, про травму) — показывается один раз '
  'наверху экрана, не копируется в описание каждой тренировки.';
