-- Отказ ученика от диагностического теста.
--
-- ПОЧЕМУ КОЛОНКА, А НЕ ФЛАГ КОМАНДЫ. Тест не обязателен: кто не хочет или не
-- может, продолжает работать по усилию. Но план перегенерируется, и флаг
-- команды пришлось бы помнить и повторять каждый раз. Забытый флаг вернул бы
-- человеку тест, от которого он уже отказался, и это выглядело бы как «тренер
-- не услышал».
--
-- Отказ снимаемый: NULL означает «не отказывался». Отдельной таблицы истории
-- здесь не заводим, потому что истории пока нет и стоить она будет дороже, чем
-- польза от неё.
alter table public.student_data_sources
  add column if not exists diagnostic_test_declined_at timestamptz;

comment on column public.student_data_sources.diagnostic_test_declined_at is
  'Ученик отказался от диагностического теста. NULL = не отказывался. Тест в план не ставится, работа идёт по усилию.';
