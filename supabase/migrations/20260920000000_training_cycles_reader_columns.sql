-- training_cycles: колонки, без которых цикл нельзя ПРОЧИТАТЬ в цель недели.
--
-- НЕ ПРИМЕНЯЕТСЯ ЭТИМ НАРЯДОМ — только файл.
--
-- ЗАЧЕМ. До этой правки строку в training_cycles вставить было можно, а прочитать нечем:
-- читателя не существовало, и сборщик всё равно брал цель недели из истории. При написании
-- читателя (lib/cycle-reader.ts) выяснилось, что двух полей физически не хватает.
--
-- start_week — с какого понедельника идёт цикл. Без него нельзя посчитать, КАКАЯ сейчас
--   неделя цикла: forecast() принимает начало ряда параметром, а роль недели (рост /
--   плановая разгрузка / подводка) определяется ПОЗИЦИЕЙ в цикле. Считать позицию от
--   created_at нельзя: тренер заводит цикл заранее и задним числом.
-- days — сколько беговых дней в неделе. Число дней — решение тренера про образ жизни
--   человека («могу бегать только до 7 утра»), а не следствие объёма. До сих пор оно
--   бралось из медианы плановой частоты по истории; при заведённом цикле это должно
--   быть то, что задал тренер. null = «как в истории», прежнее поведение.
--
-- ПОМЕТКИ ИСТОЧНИКА:
--   [практика]      — измерено по данным Игоря
--   [решение Игоря] — принято тренером
--   [выведено]      — ни то ни другое

alter table public.training_cycles
  add column if not exists start_week date,
  add column if not exists days integer;

comment on column public.training_cycles.start_week is
  'Понедельник первой недели цикла. Роль недели (рост / плановая разгрузка / подводка) считается по позиции относительно него. null — цикл читается от текущей недели. [выведено]';

comment on column public.training_cycles.days is
  'Сколько беговых дней в неделе задал тренер. null — брать из медианы плановой частоты по истории, как было до цикла. [решение Игоря]';

alter table public.training_cycles
  add constraint training_cycles_days_range check (days is null or days between 1 and 7);

-- Один активный цикл на атлета. Раньше это не было запрещено, и два активных цикла
-- на одного человека давали неопределённое поведение читателя (какой из них главный).
create unique index if not exists training_cycles_one_active_per_athlete
  on public.training_cycles (trainingpeaks_athlete_id)
  where status = 'active';
