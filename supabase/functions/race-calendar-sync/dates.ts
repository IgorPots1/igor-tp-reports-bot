// День старта из текста страницы события, когда в списке у источника диапазон дат.
//
// orgeo пишет в списке «17-18.10.2026» (день приезда/регистрации + день старта), а в тексте события —
// «18 октября 2026 года пройдёт Чемпионат…». Робот брал первый день диапазона и ставил старт на 17.10,
// федерация — 18.10. Берём день из текста, только если он ОДИН, лежит внутри диапазона и стоит рядом со
// словами «пройдёт / состоится / старт»; иначе null — остаётся диапазон из списка, ничего не угадываем.

const MONTHS: [RegExp, number][] = [
  [/^январ/, 1], [/^феврал/, 2], [/^март/, 3], [/^апрел/, 4], [/^ма[йя]/, 5], [/^июн/, 6],
  [/^июл/, 7], [/^август/, 8], [/^сентябр/, 9], [/^октябр/, 10], [/^ноябр/, 11], [/^декабр/, 12],
];

export function textDayInRange(text: string, from: string, to: string): string | null {
  if (from === to) return null;
  const t = text.replace(/\s+/g, " ");
  const re = /(\d{1,2})\s+([а-яё]+)\s+(\d{4})(?:\s*(?:г\.|года|г))?[,]?\s+(?:пройд[её]т|состоится|старт)/gi;
  const days = new Set<string>();
  for (const m of t.matchAll(re)) {
    const mon = MONTHS.find(([r]) => r.test(m[2].toLowerCase()))?.[1];
    if (!mon) continue;
    const day = `${m[3]}-${String(mon).padStart(2, "0")}-${m[1].padStart(2, "0")}`;
    if (day >= from && day <= to) days.add(day);
  }
  return days.size === 1 ? [...days][0] : null;
}
