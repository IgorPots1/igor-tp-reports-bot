/** Москва, Петербург, Севастополь: город и субъект одновременно. */
export const FEDERAL_CITIES = ["Москва", "Санкт-Петербург", "Севастополь"];

const low = (s: string) => s.toLowerCase().replace(/ё/g, "е").replace(/\s*[—–]\s*/g, " - ").replace(/\s+/g, " ").trim();

/** Похоже на название субъекта (а не города): область, край, республика, автономный округ. */
export function isSubjectName(s: string | null | undefined): boolean {
  const t = low(s || "");
  if (!t) return false;
  return /(област|(^|\s)край$|республик|автономн|(^|\s)обл\.?$|(^|\s)респ\.?(\s|$)|(^|\s)ао$)/.test(t) || t in SHORT;
}

/**
 * Каноническое название субъекта из любого написания региона; null — не субъект (город, район, пусто).
 * «Тверская обл» → «Тверская область», «Удмуртия» → «Удмуртская Республика», «респ Татарстан» →
 * «Республика Татарстан», «Москва» → «Москва».
 */
export function canonicalSubject(raw: string | null | undefined): string | null {
  const t = low(raw || "").replace(/^г\.?\s+/, "");
  if (!t) return null;
  const fed = FEDERAL_CITIES.find((c) => low(c) === t);
  if (fed) return fed;
  if (SHORT[t]) return SHORT[t];
  let m = t.match(/^(?:республика|респ\.?)\s+(.+)$/) || t.match(/^(.+?)\s+(?:республика|респ\.?)$/);
  if (m) {
    const name = m[1].trim();
    if (SHORT[name]) return SHORT[name];
    // «Удмуртская Республика», «Чувашская Республика»: прилагательное впереди
    if (/(ская|цкая)$/.test(name)) return `${cap(name)} Республика`;
    return `Республика ${capWords(name)}`;
  }
  m = t.match(/^(.+?)\s+(?:область|обл\.?)$/);
  if (m) return `${capWords(m[1])} область`;
  m = t.match(/^(.+?)\s+край$/);
  if (m) return `${capWords(m[1])} край`;
  m = t.match(/^(.+?)\s+(?:автономный округ|ао)(?:\s+-\s+(.+))?$/);
  if (m) return SHORT[t] ?? `${capWords(m[1])} автономный округ`;
  if (/автономная область$/.test(t)) return SHORT[t] ?? cap(t);
  // голое прилагательное orgeo («Тверская»): область
  if (/^[а-я-]+(ская|цкая)$/.test(t)) return `${cap(t)} область`;
  if (/^[а-я-]+(ский|цкий)$/.test(t)) return `${cap(t)} край`;
  return null;
}

/** Субъект из ответа геокодера Nominatim: сегмент перед «… федеральный округ». */
export function subjectFromDisplay(display: string | null | undefined): string | null {
  if (!display) return null;
  const segs = display.split(",").map((x) => x.trim()).filter(Boolean);
  const fo = segs.findIndex((x) => /федеральный округ/i.test(x));
  if (fo > 0) return canonicalSubject(segs[fo - 1]) ?? capWords(low(segs[fo - 1]));
  // ответ без федерального округа (Крым и новые регионы в OSM-Украине): последний сегмент-субъект
  for (const s of segs.slice().reverse()) {
    const c = canonicalSubject(s);
    if (c) return c;
  }
  return null;
}

function cap(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function capWords(s: string): string {
  return s.split(" ").map((w, i) => (i > 0 && /^(и|на|-)$/.test(w) ? w : w.split("-").map(cap).join("-"))).join(" ");
}
