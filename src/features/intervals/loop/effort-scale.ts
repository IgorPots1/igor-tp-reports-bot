const BY_CODE = new Map<string, EffortOption>(EFFORT_OPTIONS.map((option) => [option.code, option]));

export function effortByCode(code: string): EffortOption | null {
  return BY_CODE.get(code) ?? null;
}

/**
 * Вопрос про боль — ОТДЕЛЬНЫЙ, а не шестая кнопка усилия.
 *
 * Тяжело и больно — разные оси. Человек может пройти лёгкую сессию и потянуть
 * связку, и наоборот. Склеенные в одну шкалу, они дают ответ, из которого
 * нельзя понять, что делать: «тяжело» лечится повтором ступени, боль —
 * остановкой и тренером.
 *
 * Формулировка намеренно широкая («болело или мешало»): новичок не называет
 * болью то, что тренер обязан увидеть — тянуло колено, кололо в боку, натёрло.
 * Занижать порог здесь дешевле, чем пропустить травму.
 */
export type PainOption = {
  code: "no_pain" | "pain";
  labelRu: string;
  hintRu: string;
  pain: boolean;
};

export const PAIN_OPTIONS: PainOption[] = [
  {
    code: "no_pain",
    labelRu: "Ничего не беспокоило",
    hintRu: "обычная усталость не в счёт",
    pain: false,
  },
  {
    code: "pain",
    labelRu: "Что-то болело или мешало",
    hintRu: "колено, стопа, бок, спина, что угодно, даже несильно",
    pain: true,
  },
];

export function painByCode(code: string): PainOption | null {
  return PAIN_OPTIONS.find((option) => option.code === code) ?? null;
}

/**
 * Что ученице показать сразу после ответа.
 *
 * ЧЕЛОВЕКУ НЕ ГОВОРИМ «hold_for_coach» И НЕ ПОКАЗЫВАЕМ RPE. Он сказал, как
 * было; в ответ он должен получить понятное следствие, а не внутреннее
 * состояние машины.
 *
 * При боли ответ НЕ обещает, что тренер напишет: в этом наряде никакие
 * сообщения наружу не уходят автоматически, и обещать доставку, которой нет,
 * значит врать человеку, которому больно.
 */
export function checkinReplyRu(input: {
  action: "progress" | "repeat" | "step_back" | "hold_for_coach";
  stepAfter: number;
  pain: boolean;
}): string {
  if (input.pain) {
    return (
      "Записал. Раз что-то беспокоило, следующую тренировку пока не усложняю, " +
      "её посмотрит тренер. Если болит сильно или не проходит за пару дней, не бегите, напишите ему."
    );
  }
  switch (input.action) {
    case "progress":
      return `Отлично. Со следующей тренировки идём на ступень ${input.stepAfter}, бега чуть больше.`;
    case "step_back":
      return (
        `Понял, было тяжело не первый раз. Возвращаемся на ступень ${input.stepAfter}: ` +
        "это не шаг назад, это тот объём, который тело принимает."
      );
    case "hold_for_coach":
      return "Записал. Следующую тренировку пока не меняю, её посмотрит тренер.";
    case "repeat":
    default:
      return "Записал. Следующая тренировка такая же, закрепляем, пока не станет привычной.";
  }
}
