/**
 * Шкала усилия для новичка: словами, которые человек может почувствовать.
 *
 * ПОЧЕМУ НЕ RPE НАПРЯМУЮ. Шкала RPE — инструмент тренера. Человеку, который
 * бежит третью неделю в жизни, «оцени от 1 до 10» не значит ничего: у него нет
 * ни опыта, ни точки отсчёта, и он ставит 5, потому что это середина. Ответ
 * получается вежливый и бесполезный, а на нём стоит ВСЯ прогрессия.
 *
 * ЧТО ОПРЕДЕЛИЛО ЧИСЛО КНОПОК. Правило перехода (decideNextStep) различает
 * ровно четыре полосы: можно двигаться (RPE ≤ 3), двигаться аккуратно (4),
 * повторить (5), упростить (> 5). Меньше пяти кнопок — и полосы склеятся:
 * ответ перестанет нести то различие, ради которого его спрашивают. Больше —
 * и новичка просят различить то, что он различить не может.
 *
 * Пятая кнопка появилась внутри полосы «можно двигаться», а не снаружи: «совсем
 * легко» и «легко» ведут к одному решению, но человеку нужен вариант, который
 * не звучит как жалоба и не звучит как геройство. Без него все лёгкие сессии
 * собираются в одну кнопку, и тренер не видит запаса.
 *
 * ЧИСЛО — ИСТИНА, СЛОВА — ИНТЕРФЕЙС. В базу идёт и то и другое: правило
 * считает по числу, а формулировки со временем поменяются, и старые ответы
 * должны остаться читаемыми.
 */

export type EffortOption = {
  /** Код кнопки. Уходит в callback/запрос, в базе не хранится. */
  code: EffortCode;
  /** Текст на кнопке. Хранится рядом с числом. */
  labelRu: string;
  /** Подпись под кнопкой — то, по чему человек узнаёт своё состояние. */
  hintRu: string;
  /** RPE по шкале методики. */
  rpe: number;
};

export type EffortCode = "very_easy" | "easy" | "noticeable" | "hard" | "very_hard";

