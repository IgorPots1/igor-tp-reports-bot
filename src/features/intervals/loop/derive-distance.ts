/**
 * Дистанция СЧИТАЕТСЯ из скорости, а не спрашивается [наряд Игоря, 11.10.2026].
 *
 * ── ЗАЧЕМ ────────────────────────────────────────────────────────────────────
 *
 * Человек на дорожке не знает своей дистанции: на панели перед ним скорость в
 * км/ч и время. Дистанцию он прикидывает в уме, и прикидка врёт. У живой
 * ученицы это дало 8610 метров за 56 минут интервальной — 9,2 км/ч в среднем
 * при её лёгком 6,3, то есть число, восстановить из которого нечего.
 *
 * Поэтому у неё спрашиваем ровно то, что она видит, а дистанцию выводим сами и
 * ПОМЕЧАЕМ выведенной. Через месяц должно быть видно, где её число, а где наш
 * расчёт: иначе наш расчёт станет «фактом», и первый же спор о нём будет
 * неразрешим.
 *
 * ── ЧЕГО ЗДЕСЬ НЕТ ───────────────────────────────────────────────────────────
 *
 * Темпа как ВВОДИМОЙ величины. Два поля для одной величины в разных единицах
 * (темп в мин/км и скорость в км/ч) — ловушка, в которую она и попала: писала
 * в поле темпа то 9,08, то 4,5, глядя в разные колонки панели.
 */

/** Шаг плановой тренировки: сколько минут и какого рода работа. */
export type PlannedPart = {
  minutes: number;
  /** Рабочий отрезок, а не разминка, заминка или ходьба между отрезками. */
  isWork: boolean;
};

export type DerivedDistance = {
  /** Метры. null — выводить было не из чего. */
  distanceM: number | null;
  /** Средняя скорость по всей тренировке, м/с. Для отображения темпа. */
  averageSpeedMps: number | null;
  /**
   * Как считали — текстом, в запись. Не для ученицы: это след для разбора
   * через месяц, когда вопрос «откуда эта дистанция» задаст сам тренер.
   */
  howRu: string;
};

/**
 * Ровный бег: одна скорость на всё время.
 *
 * Самый частый случай и самый однозначный: что на панели, то и в расчёте.
 */
export function deriveSteady(input: { minutes: number; speedKmh: number }): DerivedDistance {
  if (!(input.minutes > 0) || !(input.speedKmh > 0)) {
    return { distanceM: null, averageSpeedMps: null, howRu: "не из чего считать" };
  }
  const km = input.speedKmh * (input.minutes / 60);
  return {
    distanceM: Math.round(km * 1000),
    averageSpeedMps: (input.speedKmh * 1000) / 3600,
    howRu: `${input.speedKmh} км/ч × ${input.minutes} мин`,
  };
}

/**
 * Интервальная: две скорости и длительности ИЗ ПЛАНА.
 *
 * ПОЧЕМУ ДВЕ, А НЕ ПО ЧИСЛУ ЗА ОТРЕЗОК. Шесть чисел человек путает: ученица
 * прислала «8,23 / 8,23 / 5,57 / 8,57 / 6,10 / 5,20», и это оказалась смесь
 * двух колонок панели, про которую нельзя сказать даже, где скорость, а где
 * темп. Два числа — «на чём шли отрезки» и «на чём восстановление» — она
 * держит в голове и не путает, а длительности мы и так знаем: их написали мы.
 *
 * ДОПУЩЕНИЕ, КОТОРОЕ ЗДЕСЬ ЕСТЬ И КОТОРОЕ НАДО ЗНАТЬ: разминка и заминка
 * считаются по скорости ВОССТАНОВЛЕНИЯ, потому что третьего числа мы не
 * спрашиваем. В её разминке есть лёгкий бег быстрее ходьбы, значит расчёт
 * ЗАНИЖАЕТ дистанцию. Занижать здесь правильнее: завышенная дистанция станет
 * основанием прибавить объём, заниженная — нет.
 */
export function deriveIntervals(input: {
  parts: PlannedPart[];
  workSpeedKmh: number;
  recoverySpeedKmh: number;
}): DerivedDistance {
  const total = input.parts.reduce((sum, part) => sum + part.minutes, 0);
  if (!(total > 0) || !(input.workSpeedKmh > 0) || !(input.recoverySpeedKmh > 0)) {
    return { distanceM: null, averageSpeedMps: null, howRu: "не из чего считать" };
  }
  const workMin = input.parts.filter((p) => p.isWork).reduce((s, p) => s + p.minutes, 0);
  const restMin = total - workMin;
  const km = input.workSpeedKmh * (workMin / 60) + input.recoverySpeedKmh * (restMin / 60);
  return {
    distanceM: Math.round(km * 1000),
    averageSpeedMps: (km * 1000) / (total * 60),
    howRu:
      `работа ${workMin} мин по ${input.workSpeedKmh} км/ч, ` +
      `остальное ${restMin} мин по ${input.recoverySpeedKmh} км/ч ` +
      `(разминка и заминка посчитаны по скорости восстановления, это занижает)`,
  };
}

/**
 * Разобрать плановую тренировку в длительности для расчёта.
 *
 * РАБОТА УЗНАЁТСЯ БЕЛЫМ СПИСКОМ, А НЕ ЧЁРНЫМ. Та же развилка, на которой уже
 * обжигались в released-work-volume.ts: «не разминка и не шаг — значит работа»
 * ошибается в сторону ЗАВЫШЕНИЯ, а завышенная дистанция ведёт к прибавке
 * объёма, которой человек не заработал.
 */
export function plannedParts(segments: Array<{ label: string; minutes: number }>): PlannedPart[] {
  return segments.map((segment) => ({
    minutes: segment.minutes,
    isWork: /^отрезок|^отрезки|темпов|порогов/iu.test(segment.label),
  }));
}
