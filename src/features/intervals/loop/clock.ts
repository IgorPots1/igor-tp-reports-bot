/**
 * «Сегодня» для контура.
 *
 * ЗОНА, А НЕ UTC. Весь контур крутится вокруг дня: карточка на сегодня, перенос
 * внутри недели, дата чек-ина. В UTC вечерняя тренировка уезжает на следующие
 * сутки, и человек в 23:30 увидел бы завтрашний план вместо сегодняшнего, а его
 * чек-ин лёг бы не на ту сессию — то есть не на ту ступень.
 *
 * Зона тренерская (та же, что у клуба и у операционных напоминаний), а не
 * ученицы: она в том же часовом поясе, а плодить ещё одно поле в анкете ради
 * разницы, которой сейчас нет, — это сложность без пользы. Когда появится
 * ученик из другой зоны, сюда придёт его зона, и это будет ОДНО место.
 */

const COACH_TIMEZONE = "Europe/Belgrade";

export function todayIsoInCoachTimezone(now: Date = new Date()): string {
  // sv-SE даёт ISO-подобный формат YYYY-MM-DD без ручной сборки из частей.
  return new Intl.DateTimeFormat("sv-SE", { timeZone: COACH_TIMEZONE }).format(now);
}

export { COACH_TIMEZONE };
