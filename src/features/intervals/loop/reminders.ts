/**
 * Напоминания: когда слать и что сказать.
 *
 * ЗАЧЕМ ОНИ ВООБЩЕ. Прогрессия в этом контуре двигается не календарём, а
 * отметками: пока человек не сказал, как далась тренировка, следующая не
 * станет сложнее. Значит забытая отметка останавливает не «статистику», а саму
 * программу. Новичок забывает не из вредности: у него ещё нет привычки, и
 * приложение он открывает не каждый день.
 *
 * ── ПОЧЕМУ ИМЕННО ДВА И ИМЕННО ТОГДА ────────────────────────────────────────
 *
 * УТРОМ — что сегодня. Не «иди беги», а «вот что на сегодня, и если день не
 * складывается, тренировку можно перенести». Утро выбрано потому, что решение
 * «когда сегодня бежать» человек принимает утром, а не вечером; вечернее
 * напоминание о тренировке приходит, когда день уже прожит, и читается как
 * упрёк.
 *
 * ВЕЧЕРОМ — отметиться. Только если тренировка была (по плану или по факту в
 * Intervals), а отметки нет. Вечер выбран потому, что к этому часу пробежка уже
 * случилась или уже не случится, и вопрос «как прошло» осмысленный в обоих
 * случаях.
 *
 * ОКНО, А НЕ ТОЧНОЕ ВРЕМЯ. Раннер просыпается раз в полчаса, ноутбук иногда
 * спит, запуск иногда пропускается. Точное «в 8:00» означало бы «не пришло
 * вовсе, если в 8:00 машина спала». Окно в два часа переживает один пропущенный
 * запуск, а от повторов защищает не аккуратность кода, а уникальный ключ в
 * базе: один вид напоминания на источник в сутки.
 *
 * ВРЕМЯ СЧИТАЕТСЯ ПО ЗОНЕ УЧЕНИЦЫ. Тренер в Белграде, ученица может быть где
 * угодно; напоминание в 8 утра по Белграду это 3 ночи во Владивостоке.
 */

export type ReminderKind =
  | "today_session"
  | "checkin_nudge"
  | "missed_nudge"
  | "plan_published"
  | "weekly_form";

/**
 * Сколько дней подряд человек пропускает, прежде чем бот замолчит.
 *
 * ПОЧЕМУ БОТ ВООБЩЕ ЗАМОЛКАЕТ [решение 15.09.2026]. Первый пропуск это бытовая
 * случайность, и мягкий вопрос уместен. Третий подряд — уже не случайность, и
 * причина почти всегда такая, которую бот не решает: заболела, уехала,
 * навалилось, передумала. Каждый следующий одинаковый вопрос от робота в этой
 * ситуации читается как «меня не слышат», и человек уходит молча.
 *
 * Поэтому после двух пропусков подряд бот молчит, а тренер видит это сигналом
 * в списке. Спросить должен человек, а не программа: только человек может
 * поменять план, поставить паузу или просто сказать «ничего страшного».
 */
export const MISSED_STREAK_SILENCE = 2;

/** Утреннее окно, по местному времени ученицы. */
export const MORNING_WINDOW = { fromHour: 7, toHour: 9 } as const;
/** Вечернее окно, по местному времени ученицы. */
export const EVENING_WINDOW = { fromHour: 19, toHour: 21 } as const;

/**
 * Воскресное окно недельной формы, по местному времени ученицы.
 *
 * ПОЧЕМУ 10–12, А НЕ УТРЕННЕЕ 7–9. В воскресенье у многих стоит длительная, и
 * в 7–9 уже уходит напоминание «сегодня по плану». Две просьбы подряд в одно
 * утро — это шум, в котором тонут обе. К десяти утра человек либо уже сбегал,
 * либо решил, что побежит позже, и вопрос про прошедшую неделю не спорит с
 * сегодняшней тренировкой.
 */
export const SUNDAY_FORM_WINDOW = { fromHour: 10, toHour: 12 } as const;

export type ReminderDecision =
  | { send: false; reason: string }
  | { send: true; kind: ReminderKind; textRu: string };

export type ReminderInput = {
  /** Местный час ученицы, 0–23. */
  localHour: number;
  /**
   * Сколько ПЛАНОВЫХ дней подряд закончились ничем: ни пробежки, ни отметки.
   * Считается по дням до сегодняшнего.
   */
  missedStreak?: number;
  /** Что стоит в плане на сегодня. null — сегодня отдыха или плана нет. */
  todaySession: { title: string; minutes: number } | null;
  /** Отметилась ли она сегодня. */
  hasCheckinToday: boolean;
  /** Приехала ли из Intervals тренировка сегодняшним днём. */
  hasActivityToday: boolean;
  /** Какие напоминания сегодня уже уходили. */
  alreadySentKinds: ReminderKind[];
  /** Опубликован ли план: без него напоминать не о чем. */
  hasPublishedPlan: boolean;
  /** Сегодня воскресенье по местному времени ученицы. */
  isSunday?: boolean;
  /** Отмечалась ли она хоть раз на этой неделе. */
  hasCheckinThisWeek?: boolean;
  /** Заполнена ли недельная форма за эту неделю. */
  hasWeeklyReportThisWeek?: boolean;
};

function inWindow(hour: number, window: { fromHour: number; toHour: number }): boolean {
  return hour >= window.fromHour && hour <= window.toHour;
}

export function decideReminder(input: ReminderInput): ReminderDecision {
  if (!input.hasPublishedPlan) {
    return { send: false, reason: "плана нет или он не опубликован" };
  }
  const sent = new Set(input.alreadySentKinds);

  // ── НЕДЕЛЬНАЯ ФОРМА ── ВЫШЕ ГЕЙТА «уже отметилась сегодня».
  //
  // Это не напоминание про отметку, а отдельный разговор про прошедшую неделю.
  // Воскресная отметка о длительной его не отменяет: она про одну тренировку,
  // а форма — про неделю целиком.
  //
  // НЕ ШЛЁМ, ЕСЛИ НА НЕДЕЛЕ НЕ БЫЛО НИ ОДНОЙ ОТМЕТКИ [решение Игоря]. Спрашивать
  // «как прошла неделя» у человека, который на этой неделе не появлялся, —
  // значит послать упрёк под видом заботы. Такой случай уходит тренеру сигналом,
  // а не боту.
  if (input.isSunday === true && inWindow(input.localHour, SUNDAY_FORM_WINDOW) && !sent.has("weekly_form")) {
    if (input.hasWeeklyReportThisWeek === true) {
      return { send: false, reason: "форма за эту неделю уже заполнена" };
    }
    if (input.hasCheckinThisWeek !== true) {
      return { send: false, reason: "на этой неделе ни одной отметки — форму не шлём, это к тренеру" };
    }
    return {
      send: true,
      kind: "weekly_form",
      textRu:
        "Неделя заканчивается. Расскажите, как она прошла: три коротких вопроса, минута времени.\n\n" +
        "Это то, чего я не вижу по отдельным тренировкам — успели ли вы по графику и не " +
        "накопилась ли усталость. От вашего ответа зависит, какой я соберу следующую неделю.",
    };
  }

  // ОТМЕТИЛАСЬ — ЗНАЧИТ НЕ ТРОГАЕМ. Оба напоминания ниже существуют ради отметки;
  // после неё любое из них становится шумом.
  if (input.hasCheckinToday) {
    return { send: false, reason: "уже отметилась сегодня" };
  }

  if (inWindow(input.localHour, MORNING_WINDOW) && !sent.has("today_session")) {
    if (!input.todaySession) {
      return { send: false, reason: "сегодня отдых, напоминать не о чем" };
    }
    return {
      send: true,
      kind: "today_session",
      textRu:
        `Сегодня по плану: ${input.todaySession.title}, ${input.todaySession.minutes} минут.\n\n` +
        "Если день не складывается, тренировку можно перенести на другой день прямо в приложении.",
    };
  }

  if (inWindow(input.localHour, EVENING_WINDOW)) {
    // ТРЕНИРОВКА БЫЛА: спрашиваем, как прошла. Это разговор о сделанном.
    if (input.hasActivityToday && !sent.has("checkin_nudge")) {
      return {
        send: true,
        kind: "checkin_nudge",
        textRu:
          "Вижу, что вы сегодня бегали. Отметьтесь, пожалуйста: одна кнопка, десять секунд.\n\n" +
          "От вашего ответа зависит, станет ли следующая тренировка сложнее. Пока отметки нет, " +
          "программа стоит на месте.",
      };
    }

    // ТРЕНИРОВКИ НЕ БЫЛО: это другой разговор, и тон у него другой.
    //
    // НЕ ПРО ОТМЕТКУ, А ПРО ЧЕЛОВЕКА. Просить отметиться о том, чего не было,
    // бессмысленно и обидно: человек и так знает, что не побежал. Спрашиваем,
    // всё ли в порядке, и не требуем ничего в ответ.
    if (!input.hasActivityToday && input.todaySession && !sent.has("missed_nudge")) {
      if ((input.missedStreak ?? 0) >= MISSED_STREAK_SILENCE) {
        return {
          send: false,
          reason: `пропусков подряд ${input.missedStreak}: бот молчит, это к тренеру`,
        };
      }
      return {
        send: true,
        kind: "missed_nudge",
        textRu:
          "Сегодня по плану была тренировка, а её не видно. У вас всё в порядке?\n\n" +
          "Если день просто не сложился, ничего страшного: догонять не нужно, продолжайте по " +
          "плану со следующей. Если что-то мешает и так будет и дальше, напишите мне, " +
          "пересоберём неделю под вашу жизнь.",
      };
    }

    return { send: false, reason: "вечером сказать нечего" };
  }

  return { send: false, reason: "не время: ждём утреннего или вечернего окна" };
}

/** Включены ли напоминания вообще. По умолчанию выключены. */
export function areRemindersEnabled(): boolean {
  return process.env.INTERVALS_REMINDERS_ENABLED === "true";
}
