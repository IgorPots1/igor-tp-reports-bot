/**
 * Что сказать ученице, когда тренер нажал «Отдать ученице».
 *
 * ── ЗАЧЕМ РАЗВИЛКА ──────────────────────────────────────────────────────────
 *
 * Текст был один: «План готов». Для новой недели это правда. Но тренер жмёт ту
 * же кнопку и тогда, когда дописывает один день в неделю, которую ученица уже
 * видит, — и человек получает «план готов» про план, который у него неделю как
 * есть. Живой случай 23.09.2026: в текущую неделю добавили одну пятницу, и
 * ученице ушло «План готов».
 *
 * ── ПОЧЕМУ СЧИТАЕМ ТРЕНИРОВКИ, А НЕ ДОВЕРЯЕМ СТАТУСУ ────────────────────────
 *
 * По статусу недели видно только «отдавали её раньше или нет». Этого хватает
 * отличить новую неделю от правки, но НЕ хватает, чтобы сказать «добавил
 * тренировку»: тренер мог и просто переписать существующую. Сказать «добавил»
 * там, где ничего не добавлено, — ровно та мелкая неправда, которая копится и
 * превращает уведомления в шум.
 *
 * Поэтому при каждой отдаче запоминается, сколько тренировок в неделе было
 * (intervals_plan_weeks.released_session_count), и в следующий раз число
 * сравнивается. Больше — «добавил». Столько же или меньше — «поправил».
 *
 * НЕИЗВЕСТНО — ЗНАЧИТ «ПОПРАВИЛ». У недель, отданных до появления колонки,
 * числа нет. Догадываться в сторону «добавил» нельзя: это утверждение о факте,
 * а факта у нас нет.
 *
 * ЧИСТАЯ ФУНКЦИЯ, БЕЗ БАЗЫ И БЕЗ СЕТИ: её гоняет check:week-notice.
 */

/** Вид уведомления. Совпадает с kind в intervals_reminders. */
export type WeekNoticeKind = "plan_published" | "week_updated";

export type WeekNotice = {
  kind: WeekNoticeKind;
  textRu: string;
};

const APP_LINE = "Откройте приложение: там ваши тренировки на неделю и кнопка отметиться после пробежки.";

/**
 * БЕЗ ПРИВЯЗКИ К «СЕГОДНЯ» [решение Игоря, 17.09.2026]: план мог начаться не
 * сегодняшним днём, и «тренировка на сегодня» в тексте — обещание, которое
 * экран может тут же не выполнить (отдых сегодня — это тоже часть плана, не
 * ошибка, см. restNoteRu в student-view.ts).
 */
const PLAN_READY = `План готов. ${APP_LINE}\n\nЕсли что-то в плане не подходит по дням, тренировку можно перенести прямо там.`;

function plural(n: number, one: string, few: string, many: string): string {
  const mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 14) return many;
  const mod10 = n % 10;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
}

export function weekNoticeOf(input: {
  /** Отдавали ли эту неделю раньше. */
  wasReleased: boolean;
  /** Сколько тренировок было в ней на момент прошлой отдачи. null — не знаем. */
  sessionsBefore: number | null;
  /** Сколько тренировок в ней сейчас. */
  sessionsAfter: number;
}): WeekNotice {
  if (!input.wasReleased) {
    return { kind: "plan_published", textRu: PLAN_READY };
  }

  const added =
    input.sessionsBefore === null ? 0 : Math.max(0, input.sessionsAfter - input.sessionsBefore);

  if (added > 0) {
    /**
     * БЕЗ СЛОВА «ЭТУ» ПРО НЕДЕЛЮ. Тренер дописывает день и в текущую неделю, и
     * в уже отданную будущую — «в эту неделю» во втором случае было бы враньём
     * про сроки, а даты человеку тут и не нужно: он сейчас откроет план.
     */
    const what =
      added === 1
        ? "тренировку. Откройте приложение, она уже в плане."
        : `${added} ${plural(added, "тренировку", "тренировки", "тренировок")}. Откройте приложение, они уже в плане.`;
    return { kind: "week_updated", textRu: `Добавил вам ${what}` };
  }

  return {
    kind: "week_updated",
    textRu: "Поправил вашу неделю. Откройте приложение, там свежая версия.",
  };
}
