// Часть А / качество углеводов: детерминированная классификация углеводного
// продукта на быстрый/медленный ПО ИМЕНИ ПРОДУКТА. Принцип проекта «код считает,
// модель пишет» распространяется и на ярлык скорости углевода: банан — это
// «быстрый», овсянка — «медленный»; это фиксированное свойство продукта, а не
// усмотрение модели. Модель может только ПОВТОРИТЬ класс, который присвоил код.
//
// Граммы углеводов берутся из PDF (item carbs) — этот модуль никогда не читает
// числа из слов ученика. Стиль и матчинг — как в activity-energy.ts: Unicode-aware
// (ASCII \b кириллицу не ловит — урок с распознаванием забегов), регэкспы с флагом
// `u` и leading-границей (?<![\p{L}]); хвост слова не ограничиваем, чтобы ловить
// русскую морфологию (гречка/гречневая/гречку), но короткие/опасные стволы
// (нут, маш) держим как целые слова.

export type CarbClass = "fast" | "slow" | "neutral" | "not_carb_base";

// Единый порог «является ли item значимым источником углеводов». Переиспользуется
// и в facts builder (carb_contributor), и здесь — один источник правды, чтобы
// дубль ≥20 не разъехался (урок #3). item ниже порога → not_carb_base, ярлык
// скорости не ставим (кусок хлеба на 5 г или борщ — не повод рассуждать о
// «быстрый/медленный»). TODO: порог тюнинговый, при обкатке можно подвинуть.
export const CARB_CONTRIBUTOR_MIN_G = 20;

// Порядок важен: FAST проверяется ПЕРВЫМ. Это защищает от главного бага (назвать
// быстрый продукт «медленным»): «овсяное печенье»/«банановый хлеб» → fast (печенье/
// банан выигрывают), а не slow. SLOW — вторым. Всё прошедшее грамм-гейт и не
// попавшее в fast/slow → neutral (дефолт для белого риса, картофеля, обычной
// пасты и любого незнакомого продукта).

const FAST_PATTERNS: RegExp[] = [
  // банан и фрукты-«быстрые»
  /(?<![\p{L}])банан/u,
  /(?<![\p{L}])(?:виноград|изюм|финик|курага|чернослив|сухофрукт|цукат)/u,
  // белый хлеб / сдоба / лаваш / батон
  /(?<![\p{L}])(?:бел(?:ый|ого|ым|ом)?\s+хлеб|батон|багет|булочк|булк[аиоуы]|сдоб|лаваш|чиабат|тортиль)/u,
  // выпечка и кондитерка
  /(?<![\p{L}])(?:выпечк|печенье|печеньк|крекер|пряник|вафл|круассан|круссан|маффин|кекс|пончик|пирожн|пирог|торт|сухар|плюшк|круж[оа]вн)/u,
  // сладкое / сахар
  /(?<![\p{L}])(?:сахар|сладк|конфет|шоколад|шокол|мармелад|зефир|пастил|варень|джем|повидл|сгущ|сироп|халв|нутелл|карамел|ирис(?![\p{L}])|щербет|шербет|драже|мёд(?![\p{L}])|мед(?![\p{L}]))/u,
  // мороженое
  /(?<![\p{L}])(?:мороженое|мороженого|пломбир|эскимо)/u,
  // сладкие напитки / соки
  /(?<![\p{L}])(?:сок|фреш|газировк|кола(?![\p{L}])|пепси|лимонад|морс|компот|нектар|энергетик)/u,
];

const SLOW_PATTERNS: RegExp[] = [
  // овёс
  /(?<![\p{L}])(?:овсян|геркулес|овёс(?![\p{L}])|овс(?![\p{L}]))/u,
  // гречка (не «грецкий» — там ц)
  /(?<![\p{L}])греч/u,
  // цельнозерновой / ржаной хлеб, хлебцы, отруби
  /(?<![\p{L}])(?:цельнозерн|цельно-зерн|цельнозлак|ржан|бородинск|отрубн|отруб(?![\p{L}])|хлебц|зернов\p{L}*\s+хлеб)/u,
  // бурый/коричневый/дикий рис (белый рис → neutral дефолтом)
  /(?<![\p{L}])(?:бур\p{L}*\s+рис|коричнев\p{L}*\s+рис|дик\p{L}*\s+рис)/u,
  // бобовые
  /(?<![\p{L}])(?:чечевиц|нут|маш(?![\p{L}])|фасол|горох|бобов|нохут)/u,
  // прочие медленные крупы
  /(?<![\p{L}])(?:перлов|булгур|кускус|кус-кус|киноа|кинва|полб|спельт|пшён|пшен|ячнев|ячмен)/u,
];

function matchesAny(haystack: string, patterns: RegExp[]): boolean {
  return patterns.some((pattern) => pattern.test(haystack));
}

/**
 * Классифицирует углеводный продукт по имени + содержанию углеводов (из PDF).
 * Порядок: грамм-гейт → fast → slow → neutral (дефолт).
 */
export function classifyCarbItem(
  name: string | null | undefined,
  carbsGrams: number | null | undefined
): CarbClass {
  // 1) Грамм-гейт первым: слишком мало углеводов, чтобы рассуждать о «скорости».
  if (typeof carbsGrams !== "number" || !Number.isFinite(carbsGrams) || carbsGrams < CARB_CONTRIBUTOR_MIN_G) {
    return "not_carb_base";
  }
  const hay = (name ?? "").toLowerCase().trim();
  if (hay.length < 2) {
    return "neutral";
  }
  // 2) Гейт пройден → fast побеждает slow при совпадении (защита от «медленным»).
  if (matchesAny(hay, FAST_PATTERNS)) {
    return "fast";
  }
  if (matchesAny(hay, SLOW_PATTERNS)) {
    return "slow";
  }
  return "neutral";
}
