/**
 * Схема вердиктов — раздел 2 наряда «Сбор базы кроссовок, версия 2».
 *
 * База строится не из измерений, а из свода обзоров. Это не хуже и не лучше
 * измерения, это другое: обзор субъективен, но покрывает то, чего не меряет ни
 * один прибор — как модель ведёт себя на длинной, кому натирает, насколько
 * живучая.
 *
 * Отсюда главное свойство схемы: у КАЖДОГО вердикта должно быть не меньше двух
 * прочитанных обзоров со ссылками. Утраченную объективность измерений заменяет
 * проверяемость: человек видит, на чём основан вывод.
 */

export type Purpose = "daily" | "tempo" | "race" | "max" | "stability" | "trail" | "winter";
export type Feel = "firm_responsive" | "balanced" | "soft_stable" | "bouncy_soft" | "plush";
export type Width = "narrow" | "standard" | "wide";
export type Durability = "low" | "average" | "high";
export type HeelHold = "loose" | "good" | "stiff";
export type WinterGrip = "poor" | "fair" | "good";

/**
 * Жёсткость 1–5: 1 — жёстко, 5 — очень мягко.
 *
 * НАПРАВЛЕНИЕ ЗАДАЁТ ОПРОСНИК (решение Игоря, 14.10.2026): там «1 жёстко и
 * отзывчиво … 5 максимум мягкости», и вердикт пишется в той же шкале, чтобы
 * ответ и вердикт сравнивались напрямую, без переворотов в коде. До 14.10
 * шкала шла наоборот (1 очень мягкая), и тезис «ощутимо жёсткая» снимался при
 * firmness ≤ 2 — то есть у МЯГКИХ моделей.
 *
 * 1–5, а не 1–10: обзоры не дают точности на десять делений, а видимость
 * точности хуже её отсутствия.
 */
export type Firmness = 1 | 2 | 3 | 4 | 5;

/**
 * weight_class УДАЛЁН из схемы (решение Игоря, 13.10.2026). Обзоры о весе
 * бегуна прямо почти не говорят — на 20 моделях поле не заполнилось ни разу, —
 * а выводить его не из чего: стека в базе больше нет. Критерий веса бегуна в
 * движке работает теперь на durability, purpose и явном упоминании в not_for.
 */
export type Verdicts = {
  purpose: Purpose[];
  feel: Feel | null;
  firmness: Firmness | null;
  width: Width | null;
  durability: Durability | null;
  heel_hold: HeelHold | null;
  best_for: string[];
  not_for: string[];
  /**
   * Только для моделей с назначением trail или winter, либо при ЯВНОМ
   * упоминании снега, льда или зимы в обзоре. «Хорошее сцепление на мокром» —
   * это не зима: асфальт после дождя и наледь — разные покрытия, и поставить
   * зимний вердикт дорожной модели по слову «wet» значит дать человеку совет,
   * которого не давал ни один обзор.
   */
  winter_grip: WinterGrip | null;
  summary: string | null;
};

/** Доказательство: какой вердикт, из какого обзора, когда вышел. */
export type Evidence = {
  field: keyof Verdicts;
  url: string;
  source: string;
  /** Название площадки для карточки («на чём основано»). */
  source_title?: string;
  /** Дата публикации обзора. Нужна и как год модели на этапе разбора. */
  date: string | null;
  /** Кусок текста, по которому вердикт поставлен, — чтобы можно было проверить. */
  quote: string | null;
};

/**
 * Уверенность. "low" — вердикт стоит на ОДНОМ обзоре; такая модель не
 * показывается первой позицией в слоте. Для китайских брендов это ожидаемое
 * состояние, а не дефект: обзоров по ним мало.
 */
export type Confidence = "normal" | "low";

export type VerdictRecord = {
  id: string;
  brand: string;
  model: string;
  /** Год модели. Берётся при разборе: дата обзора, сверенная с сайтом бренда. */
  year: number | null;
  /**
   * Откуда год. Пишется рядом, потому что надёжность у источников разная:
   * дата публикации обзора — приближение, год из текста обзора («available
   * July 2025») — заявление, страница бренда — факт.
   */
  year_source: "review_date" | "review_text" | "brand_site" | null;
  /** Год из даты обзора и год из текста разошлись — в отчёт человеку. */
  year_conflict: string | null;
  verdicts: Verdicts;
  evidence: Evidence[];
  confidence: Confidence;
  /** Поля, где обзоры разошлись: в отчёт человеку, а не усреднять. */
  disputed: string[];
  /**
   * Поля, значение которых поставил человек, разбирая спор. Пишется рядом с
   * вердиктом, чтобы было видно: это не свод обзоров, а решение Игоря,
   * принятое, когда обзоры разошлись и четвёртый источник не помог.
   */
  decided_by: Partial<Record<keyof Verdicts, "igor">>;
  /**
   * Черновик тренерского каталога (решение Игоря, 14.10.2026). Прочитанное
   * идёт не прямо в подбор, а черновиком: Игорь подтверждает. В подбор
   * попадает только confirmed. Один источник для черновика — нормально.
   */
  status: "draft" | "confirmed";
  confirmed_by?: "igor";
  confirmedAt?: string;
};

