// Данные бегового клуба для публичных страниц. Менять цену — здесь.
//
// До этого «5 000 ₽» было прописано руками в трёх местах /landing (ценовая
// карточка, ответ в FAQ и подпись над формой), и при смене цены они разъезжались.
// Сделано по образцу src/lib/flow.ts, где так же живут данные потока интенсива.

// Неразрывный пробел экранированной последовательностью, а не литеральным
// символом: literal NBSP в исходнике неотличим от обычного пробела и теряется
// при первой же правке. Цена не должна разрываться переносом строки — ни между
// разрядами («5 / 000»), ни перед знаком рубля. В FAQ и в подписи над формой
// цена стоит внутри предложения, где перенос как раз вероятен.
const NBSP = "\u00A0";

export const CLUB = {
  /** Цена сопровождения в месяц, готовая к выводу: «5 000 ₽». */
  priceMonthly: `5${NBSP}000${NBSP}₽`,
};
